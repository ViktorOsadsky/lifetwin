# Write app/lib/room/room_layout_data.dart from app/assets/scene/room/room_layers.json.
# usage: python3 -I tools/art/room3d/gen_room_layout.py app/assets/scene/room/room_layers.json app/lib/room/room_layout_data.dart
import json, sys
d = json.load(open(sys.argv[1]))
f = lambda v: repr(float(v))
pt = lambda p: f'Offset({f(p[0])}, {f(p[1])})'
rect = lambda r: f'Rect.fromLTWH({f(r[0])}, {f(r[1])}, {f(r[2])}, {f(r[3])})'
box = lambda b: f'Rect.fromLTRB({f(b[0])}, {f(b[1])}, {f(b[2])}, {f(b[3])})'
L = d['layers']; c = d['camera']
out = f'''// GENERATED by tools/art/room3d/gen_room_layout.py from
// assets/scene/room/room_layers.json. Do not edit by hand; re-render instead.
//
// World units are the prototype's metres: x to the right wall, z toward the
// viewer, y up; the floor is y = 0. Floor points are Offset(x, z). Screen
// units are logical px of the 390 x 844 render.
import 'package:flutter/painting.dart';

import 'room_layout.dart';

const _viewProjection = <double>[{', '.join(f(v) for v in d['viewProjection'])}];

const RoomLayout roomLayout = RoomLayout(
  viewport: Size({f(d['viewport'][0])}, {f(d['viewport'][1])}),
  viewProjection: _viewProjection,
  cameraAzimuth: {f(c['az'])},
  cameraPitchDeg: {f(c['pitchDeg'])},
  bearHeight: {f(d['bearHeight'])},
  leanDeg: {f(d['leanDeg'])},
  sleepY: {f(d['sleepY'])},
  bedTop: {f(d['bed']['top'])},
  tableZ: {f(d['table']['z'])},
  bounds: {box(d['bounds'])},
  obstacles: [{', '.join(box(b) for b in d['obstacles'])}],
  waypoints: [{', '.join(pt(p) for p in d['waypoints'])}],
  wander: [{', '.join(pt(p) for p in d['wander'])}],
  spots: {{{', '.join(f"'{k}': {pt(v)}" for k, v in d['spots'].items())}}},
  bgAsset: '{L['bg']['asset']}',
  fgBed: RoomLayer('{L['fgBed']['asset']}', {rect(L['fgBed']['rect'])}),
  fgTable: RoomLayer('{L['fgTable']['asset']}', {rect(L['fgTable']['rect'])}),
  shelfEmpty: RoomLayer('{L['shelfEmpty']['asset']}', {rect(L['shelfEmpty']['rect'])}),
);
'''
open(sys.argv[2], 'w').write(out)
