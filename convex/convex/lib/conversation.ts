// Only these exact replies confirm pending answers; anything vaguer re-asks.
const AFFIRMATIVES = new Set([
  "yes",
  "yeah",
  "yep",
  "yes please",
  "correct",
  "yes correct",
  "that's correct",
  "that is correct",
  "yes that's correct",
  "yes that is correct",
  "that's right",
  "that is right",
  "yes that's right",
  "yes that is right",
  "yes it is",
]);
const NEGATIVE = new RegExp(`^(?:(?:no|nope)(?!${W})${WS}*(?:(?:it's|it is|actually|i meant)(?!${W})${WS}*)?([^\n]*))$`, "u");
const BOTH_BP: ProfileField[] = ["systolic_bp", "diastolic_bp"];
const BOTH_BP_MESSAGE = 'Please tell me both blood pressure numbers, for example "120 over 80".';
const SEX_WORDS: Record<string, string> = {
  female: "woman (female)",
  male: "man (male)",
  intersex: "intersex",
  prefer_not_to_say: "prefer not to say",
};
const SMOKING_WORDS: Record<string, string> = {
  never: "never smoked",
  former: "smoked in the past",
  current: "smoke now",
  unknown: "not sure",
};

const LIMITATIONS = [
  "Speech capture and playback are not implemented; final transcripts use the text path.",
  "Prediction functionality is deferred. No forecast is generated by intake.",
  "State is held by the caller. The server does not retain your conversation.",
];

function plain(value: number, digits = 1): string {
  return rstripChars(rstripChars(pyFixed(value, digits), "0"), ".");
}

function about(value: number, shown: string): string {
  return Math.abs(value - Number(shown)) < 0.01 ? "" : "about ";
}

function count(value: number, unit: string): string {
  return value === 0 ? "none" : `${plain(value)} ${unit}${value === 1 ? "" : "s"}`;
}

function both(metric: string, imperial: string, metricExact: boolean, imperialExact: boolean): string {
  // The unit the person used converts exactly, so it is shown first.
  if (metricExact && !imperialExact) return `${metric} (${imperial})`;
  return `${imperial} (${metric})`;
}

function height(cm: number): string {
  const inches = cm / 2.54;
  const roundedInches = pyRoundInt(inches);
  const shownIn = String(roundedInches);
  const shownCm = plain(cm, 0);
  const feet = Math.floor(roundedInches / 12);
  const rest = roundedInches - feet * 12;
  const imperial = `${about(inches, shownIn)}${feet} feet` + (rest ? ` ${rest} inches` : "");
  const metric = `${about(cm, shownCm)}${shownCm} cm`;
  return both(metric, imperial, !about(cm, shownCm), !about(inches, shownIn));
}

function weight(kg: number): string {
  const pounds = kg / 0.45359237;
  const shownLb = plain(pounds);
  const shownKg = plain(kg);
  const imperial = `${about(pounds, shownLb)}${shownLb} pounds`;
  const metric = `${about(kg, shownKg)}${shownKg} kg`;
  return both(metric, imperial, !about(kg, shownKg), !about(pounds, shownLb));
}

/** Plain-language summary in the person's own unit, metric value beside it. */
export function describe(values: Profile): string {
  const parts: string[] = [];
  for (const [field, value] of Object.entries(values) as [ProfileField, any][]) {
    if (field === "diastolic_bp" && "systolic_bp" in values) continue;
    if (field === "systolic_bp" && "diastolic_bp" in values) {
      parts.push(`Blood pressure: ${value} over ${values.diastolic_bp}`);
      continue;
    }
    const shown = {
      age: (v: number) => String(v),
      sex: (v: string) => SEX_WORDS[v],
      height_cm: height,
      weight_kg: weight,
      sleep_hours: (v: number) => `${plain(v)} hour${v === 1 ? "" : "s"} a night`,
      exercise_minutes_weekly: (v: number) => count(v, "minute") + " a week",
      smoking_status: (v: string) => SMOKING_WORDS[v],
      alcohol_drinks_weekly: (v: number) => count(v, "drink") + " a week",
      diabetes: (v: boolean) => (v ? "yes" : "no"),
      systolic_bp: (v: number) => String(v),
      diastolic_bp: (v: number) => String(v),
    }[field](value as never);
    const label = FRIENDLY_LABELS[field];
    parts.push(`${label[0].toUpperCase()}${label.slice(1)}: ${shown}`);
  }
  return parts.join("; ");
}

export type ProviderStatus = "not_configured" | "consent_required" | "used" | "unavailable" | "not_needed";

export interface TurnResponse {
  schema_version: "1.0";
  state: ConversationState;
  message: string;
  guide_mode: "guided" | "llm";
  provider_status: ProviderStatus;
  voice_status: "deferred";
  accepted_input_modes: ["text", "transcript"];
  mascot_events: { state: string; caption: string }[];
  complete: boolean;
  limitations: string[];
}

function cloneState(state: ConversationState): ConversationState {
  return {
    phase: state.phase,
    confirmed_profile: { ...state.confirmed_profile },
    pending_profile: { ...state.pending_profile },
    current_field: state.current_field,
    skipped_fields: [...state.skipped_fields],
  };
}

function invalid(message: string): never {
  throw new ApiHttpError(409, "invalid_conversation_transition", message);
}

function advance(state: ConversationState): void {
  state.current_field =
    FIELDS.find((field) => state.confirmed_profile[field] === null && !state.skipped_fields.includes(field)) ?? null;
  state.phase = state.current_field ? "asking" : "ready";
}

function prompt(state: ConversationState): string {
  if (state.phase === "confirming") {
    return "Here is what I heard. " + describe(compact(state.pending_profile)) + ". Is that right? Say yes, or tell me the right answer.";
  }
  if (state.phase === "ready") {
    return (
      "All done! I saved the answers you confirmed and left skipped ones blank. " +
      "Forecasts are not available yet. You can still change any answer."
    );
  }
  return QUESTIONS[state.current_field!];
}

function bpOrdered(state: ConversationState, pending: Profile): boolean {
  const systolic = pending.systolic_bp ?? state.confirmed_profile.systolic_bp;
  const diastolic = pending.diastolic_bp ?? state.confirmed_profile.diastolic_bp;
  return systolic === null || systolic === undefined || diastolic === null || diastolic === undefined || (systolic as number) > (diastolic as number);
}

/** Deadline for a provider call; mirrors asyncio.timeout around extract(). */
async function withTimeout<T>(seconds: number, work: (signal: AbortSignal) => Promise<T>): Promise<T> {
  // Abort the provider call itself and wait for it to settle, so no request
  // is left dangling (Convex warns about unawaited fetches).
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), seconds * 1000);
  try {
    return await work(controller.signal);
  } catch (error) {
    if (controller.signal.aborted) throw new ExtractionUnavailable();
    throw error;
  } finally {
    clearTimeout(timer);
  }
}

export class ConversationService {
  readonly timeout: number;

  constructor(
    readonly extractor: Extractor | null = null,
    timeoutSeconds = 6,
  ) {
    this.timeout = Math.max(0.1, Math.min(timeoutSeconds, 10.0));
  }

  async turn(request: TurnRequest): Promise<TurnResponse> {
    let state = cloneState(request.state);
    let mode: "guided" | "llm" = "guided";
    const configured = this.extractor !== null && this.extractor.configured;
    let providerStatus: ProviderStatus = configured ? "not_needed" : "not_configured";
    let action = request.action;
    let text = normalizeText(request.text ?? "");

    const respond = (message: string): TurnResponse => {
      const reaction = {
        idle: "idle",
        asking: "asking",
        confirming: "confirming",
        ready: "celebrating",
        cancelled: "idle",
      }[state.phase];
      return {
        schema_version: "1.0",
        state,
        message,
        guide_mode: mode,
        provider_status: providerStatus,
        voice_status: "deferred",
        accepted_input_modes: ["text", "transcript"],
        mascot_events: [{ state: reaction, caption: message }],
        complete: state.phase === "ready",
        limitations: [...LIMITATIONS],
      };
    };
    const pendingFields = () => Object.keys(compact(state.pending_profile)) as ProfileField[];

    if (action === "cancel") {
      // Clear drafts and supplied health data from the returned session.
      state = newState("cancelled");
      return respond("We can stop here. Your conversation state is cleared. Come back whenever you like.");
    }
    if (action === "start") {
      if (state.phase === "cancelled" || state.phase === "idle") {
        state.pending_profile = emptyProfile();
        advance(state);
      }
      return respond(
        "Hi, I'm your twin's guide! You can type or talk to me. " +
          "You can skip any question, and I'll check each answer with you before I save it. " +
          prompt(state),
      );
    }
    if (state.phase === "idle" || state.phase === "cancelled") invalid("Start the conversation before sending another action.");
    if (action === "reply" && state.phase === "confirming") {
      // A spoken or typed "yes" confirms; "no, ..." corrects; nothing vague confirms.
      const phrase = pySplit(rstripChars(text.toLowerCase().replace(/,/g, " "), ".!?")).join(" ");
      if (AFFIRMATIVES.has(phrase)) {
        action = "confirm";
      } else {
        const negative = NEGATIVE.exec(phrase);
        if (negative) {
          text = pyStrip(negative[1]);
          if (!text) {
            const fields = pendingFields();
            if (fields.length === 1) {
              const field = fields[0];
              return respond(
                "Okay, nothing has changed. Please tell me the right answer for " +
                  `your ${FRIENDLY_LABELS[field]}, for example ${EXAMPLES[field]}.`,
              );
            }
            if (fields.join() === BOTH_BP.join()) return respond("Okay, nothing has changed. " + BOTH_BP_MESSAGE);
            return respond(
              "Okay, nothing has changed. Which answer should I change? " +
                'Please say its name and the right answer, like "weight: 150 pounds".',
            );
          }
        }
        action = "correct";
      }
    }
    if (action === "confirm") {
      if (state.phase !== "confirming") invalid("There are no pending answers to confirm.");
      const additions = compact(state.pending_profile);
      const merged = validateProfile({ ...state.confirmed_profile, ...additions }, [], []);
      // FastAPI raises an unhandled ValidationError (HTTP 500) for a crafted
      // state whose merged blood pressure is out of order; keep that behavior.
      if (merged === null) throw new Error("merged profile failed validation");
      state.confirmed_profile = merged;
      state.pending_profile = emptyProfile();
      state.skipped_fields = state.skipped_fields.filter((field) => !(field in additions));
      advance(state);
      return respond("Confirmed! " + prompt(state));
    }
    if (action === "import") {
      if (state.phase === "confirming") invalid("Confirm or correct the pending answer before adding more.");
      const asked = state.current_field;
      const additions = compact(request.values!);
      const merged = validateProfile({ ...state.confirmed_profile, ...additions }, [], []);
      if (merged === null) throw new Error("merged profile failed validation");
      state.confirmed_profile = merged;
      state.skipped_fields = state.skipped_fields.filter((field) => !(field in additions));
      advance(state);
      // Stay on the question the person was answering if it is still open,
      // rather than jumping back to an earlier one (PR #22).
      if (asked && state.confirmed_profile[asked] === null && !state.skipped_fields.includes(asked)) {
        state.current_field = asked;
        state.phase = "asking";
      }
      const count = Object.keys(additions).length === 1 ? "1 answer" : `${Object.keys(additions).length} answers`;
      // Asking the same question again without saying why feels like being stuck.
      const missing =
        asked && state.current_field === asked
          ? `Your Health app didn't have your ${FRIENDLY_LABELS[asked]}, so I still need it. `
          : "";
      return respond(
        `Thanks! I added ${count} you checked from your Health app: ` + describe(additions) + ". " + missing + prompt(state),
      );
    }
    if (action === "skip") {
      const target = request.field ?? state.current_field;
      if (target === null) invalid("Choose a field to skip.");
      if (state.phase === "confirming") invalid("Confirm or correct pending answers before skipping a question.");
      if (state.confirmed_profile[target!] !== null) invalid("Skipping does not erase confirmed measurements.");
      if (!state.skipped_fields.includes(target!)) state.skipped_fields.push(target!);
      advance(state);
      return respond("That's okay; I won't fill it in. " + prompt(state));
    }
    if (state.phase === "ready" && action !== "correct") {
      invalid("The conversation is ready. Use correct with a field to change an answer.");
    }
    if (state.phase === "confirming" && action !== "correct") invalid("Confirm or correct the pending answers first.");
    let target = request.field ?? state.current_field;
    if (action === "correct" && state.phase === "confirming" && request.field === null) {
      let fields = pendingFields();
      if (fields.join() === BOTH_BP.join()) {
        // A pending reading is corrected as a whole pair, never one guessed half.
        if (Object.keys(parseReply(text, "systolic_bp")).length !== 2) return respond(BOTH_BP_MESSAGE + " Nothing has changed.");
        fields = ["systolic_bp"];
      }
      if (fields.length !== 1) {
        return respond(
          "I have more than one answer waiting: " +
            fields.map((field) => FRIENDLY_LABELS[field]).join(", ") +
            ". Which one do you want to change? Nothing has changed.",
        );
      }
      target = fields[0];
    }
    if (target === null) invalid("Choose the field you want to correct.");
    const field = target!;
    if (isSkip(text, field)) {
      if (action === "correct") {
        if (request.field && state.confirmed_profile[field] !== null) {
          // An explicitly chosen saved answer may be withdrawn to blank.
          state.confirmed_profile = { ...state.confirmed_profile, [field]: null } as FullProfile;
          if (!state.skipped_fields.includes(field)) state.skipped_fields.push(field);
          if (state.phase !== "confirming") advance(state);
          return respond(
            `Okay, I removed your ${FRIENDLY_LABELS[field]} answer and left it ` +
              "blank. If that was a mistake, just tell me the answer again. " +
              prompt(state),
          );
        }
        return respond("Nothing has changed. " + prompt(state));
      }
      if (!state.skipped_fields.includes(field)) state.skipped_fields.push(field);
      advance(state);
      return respond("I'll leave that unknown. " + prompt(state));
    }
    let candidates = parseReply(text, field);
    if (Object.keys(candidates).length === 0 && configured) {
      if (request.provider_consent) {
        try {
          const extraction = await withTimeout(this.timeout, (signal) => this.extractor!.extract(text, field, signal));
          candidates = groundedCandidates(text, extraction, field);
          // The helper answered; finding no usable value is not an outage.
          providerStatus = "used";
          if (Object.keys(candidates).length > 0) mode = "llm";
        } catch (error) {
          if (!(error instanceof ExtractionUnavailable)) throw error;
          providerStatus = "unavailable";
        }
      } else {
        providerStatus = "consent_required";
      }
    }
    if (Object.keys(candidates).length === 0) {
      let notice = "";
      if (providerStatus === "consent_required") {
        notice = "I can ask an AI helper to read this answer, but only if you say it's okay. ";
      } else if (providerStatus === "unavailable") {
        notice = "The AI helper isn't available right now, but we can keep going. ";
      }
      const hint = clarify(text, field);
      if (state.phase === "confirming") {
        return respond(notice + (hint ? hint + " " : "Sorry, I didn't understand that. ") + "Nothing has changed. " + prompt(state));
      }
      return respond(
        notice + (hint || "Sorry, I didn't understand that. You can answer in your own words, " + 'or say "skip". ' + QUESTIONS[field]),
      );
    }
    if (action === "correct" && request.field && !(request.field in candidates)) {
      return respond("Please give the right answer for your " + FRIENDLY_LABELS[request.field] + ". " + QUESTIONS[request.field]);
    }
    // Corrections replace affected pending values; unrelated pending values stay visible.
    const pending: Profile = { ...compact(state.pending_profile), ...candidates };
    if (!bpOrdered(state, pending)) {
      return respond(BP_ORDER_MESSAGE + " Nothing has changed. " + (state.phase === "confirming" ? prompt(state) : QUESTIONS[field]));
    }
    state.pending_profile = fullProfile(pending);
    state.phase = "confirming";
    const keys = Object.keys(pending) as ProfileField[];
    state.current_field = keys.length === 1 ? keys[0] : null;
    return respond(prompt(state));
  }
}
