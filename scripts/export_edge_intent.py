"""Export the yes/no reader's data and its 187-reply matrix for the Supabase port.

``intent-data.json`` is what ``intent.ts`` reads: the lexicon in reading order, the
questions, the tone and split patterns, the Claude prompt and schema. The matrix fixture
holds every reply of ``server/tests/test_yes_no_intent.py`` with the server's own reading,
by the rules alone and through the Claude path with the test's stub, so the Deno test
can require the same answer on every row. Run in the locked server environment;
``--check`` compares parsed JSON so Deno formatting cannot cause drift. No request data
or credentials are read, and no network call is made (Claude is the test's stub).
"""

import argparse
import asyncio
import importlib.util
import json
from pathlib import Path

from lifetwin.core import intent
from lifetwin.onboarding import service as onboarding

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "supabase/functions/lifetwin-api/intent-data.json"
MATRIX = ROOT / "contracts/fixtures/yes-no-intent.json"
MATRIX_TEST = ROOT / "server/tests/test_yes_no_intent.py"


def question(q: intent.Question) -> dict:
    return {
        "kind": q.kind,
        "text": q.text,
        "yes_means": q.yes_means,
        "no_means": q.no_means,
        "echo": list(q.echo),
        "extra": [list(pair) for pair in q.extra],
        "check": q.check,
    }


def export_data() -> dict:
    named = [
        intent.MEMORY,
        intent.OUTSIDE_AI,
        intent.VOICE,
        intent.HEALTH_OFFER,
        intent.MISSING,
        intent.ANYTHING_ELSE,
        intent.ALSO_UPDATE,
        intent.KEEP_GOING,
    ]
    return {
        "YES_FLOOR": intent.YES_FLOOR,
        "NO_FLOOR": intent.NO_FLOOR,
        # Already sorted: by tier, then longest pattern first.
        "lexicon": [[p, pol, c, t, w] for _, p, pol, c, t, w in intent._LEXICON],
        "questions": {q.kind: question(q) for q in named},
        "read_back": question(intent.read_back("")),
        "patterns": {
            "fillers": intent._FILLERS.pattern,
            "joking": intent._JOKING.pattern,
            "annoyed": intent._ANNOYED.pattern,
            "eager": intent._EAGER.pattern,
            "self_correction": intent._SELF_CORRECTION.pattern,
            "contrast": intent._CONTRAST.pattern,
        },
        "prompt": intent.INTENT_PROMPT,
        "schema": intent.INTENT_SCHEMA,
        "lines": {
            "MEMORY_UNCLEAR": onboarding.MEMORY_UNCLEAR,
            "NOT_CAUGHT": onboarding.NOT_CAUGHT,
        },
    }


def reading(result: intent.IntentResult) -> dict:
    return {
        "intent": result.intent,
        "confidence": result.confidence,
        "tone": result.tone,
        "corrected_value": result.corrected_value,
        "source": result.source,
        "clear_yes": result.clear_yes,
        "clear_no": result.clear_no,
    }


def export_matrix() -> dict:
    spec = importlib.util.spec_from_file_location("yes_no_matrix", MATRIX_TEST)
    tests = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(tests)
    stub = tests.StubClaude(
        {
            t: tests.claude_answer(truth, value=t if truth == "correction" else None)
            for _, t, truth, _ in tests.CASES
        }
    )
    rows = []
    for name, text, truth, alternatives in tests.CASES:
        q = tests.QUESTIONS[name]
        before = len(stub.calls)
        claude = asyncio.run(intent.read_intent(text, q, tests.reader(stub), allowed=True))
        rows.append(
            {
                "question": name,
                "reply": text,
                "truth": truth,
                "alternatives": sorted(alternatives),
                "rules": reading(intent.read_local(text, q)),
                "claude_path": {**reading(claude), "asked_claude": len(stub.calls) > before},
            }
        )
    return {
        "about": "Generated by scripts/export_edge_intent.py from "
        "server/tests/test_yes_no_intent.py; the Claude path uses the test's stub, "
        "which answers each reply's true intent.",
        "questions": {
            name: {"kind": q.kind, "text": q.text} for name, q in tests.QUESTIONS.items()
        },
        "rows": rows,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the saved export is stale")
    args = parser.parse_args()
    exports = {DATA: export_data(), MATRIX: export_matrix()}
    if args.check:
        stale = [
            path
            for path, content in exports.items()
            if not path.exists() or json.loads(path.read_text()) != content
        ]
        for path in stale:
            print(f"{path.relative_to(ROOT)} is stale; run scripts/export_edge_intent.py")
        return 1 if stale else 0
    for path, content in exports.items():
        path.write_text(json.dumps(content, ensure_ascii=False, indent=2) + "\n")
    print(f"Exported the yes/no reader data and {len(exports[MATRIX]['rows'])} matrix rows.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
