#!/bin/zsh
# Generates silent speech clips (files only) and audio_data.dart. Run from this directory.
set -e
cd "$(dirname "$0")"
clips=(
 "what|what?"
 "born|I was born in nineteen fifty two"
 "sixty|no, sixty"
 "sex|female"
 "height|five foot four"
 "weight|a hundred and forty five pounds"
 "sleep|about seven hours"
 "exercise|I walk thirty minutes five days a week"
 "smoking|I used to smoke but I quit years ago"
 "alcohol|two glasses of wine a week"
 "diabetes|no"
 "bp|one thirty over eighty five"
 "chatter|hey can you pass me that. Female."
)
out=audio_data.dart
echo "// GENERATED by gen_audio.sh: 16 kHz mono PCM16 WAV clips as base64. Do not edit." > $out
echo "const Map<String, String> voiceClips = {" >> $out
for c in $clips; do
  k=${c%%|*}; t=${c#*|}
  say -v Samantha -r 170 -o audio/$k.aiff "$t"
  afconvert -f WAVE -d LEI16@16000 -c 1 audio/$k.aiff audio/$k.wav
  rm audio/$k.aiff
  echo "  '$k': '$(base64 -i audio/$k.wav | tr -d '\n')'," >> $out
done
echo "};" >> $out
